# --- Raster helpers -----------------------------------------------------------
def premul(rgba):
    out = rgba.copy()
    out[..., :3] *= rgba[..., 3:4]
    return out


def unpremul(p):
    out = p.copy()
    a = p[..., 3:4]
    out[..., :3] = np.where(a > 1e-6, p[..., :3] / np.maximum(a, 1e-6), 0)
    return np.clip(out, 0, 1)


def warp(arr, scale, src_anchor, dst_anchor, out_size, resample=Image.BICUBIC):
    """Affine-warp a float array (H,W,C) or (H,W): dst = (src-src_anchor)*scale + dst_anchor."""
    single = arr.ndim == 2
    if single:
        arr = arr[..., None]
    inv = 1.0 / scale
    sx, sy = src_anchor
    dx, dy = dst_anchor
    # PIL affine maps output -> input, as x_in = a*x + b*y + c
    coeffs = (inv, 0, sx - dx * inv, 0, inv, sy - dy * inv)
    chans = []
    for c in range(arr.shape[2]):
        im = Image.fromarray(arr[..., c].astype(np.float32), mode="F")
        chans.append(np.asarray(im.transform((out_size, out_size), Image.AFFINE, coeffs, resample=resample)))
    out = np.clip(np.dstack(chans), 0, 1)
    return out[..., 0] if single else out


def resize_premul(p, size):
    chans = [
        np.asarray(Image.fromarray(p[..., c].astype(np.float32), mode="F").resize((size, size), Image.LANCZOS))
        for c in range(p.shape[2])
    ]
    return np.clip(np.dstack(chans), 0, 1)


def to_image(rgba):
    return Image.fromarray((np.clip(rgba, 0, 1) * 255).round().astype(np.uint8), "RGBA")


def over(top_p, bottom_p):
    """Premultiplied 'over'."""
    return top_p + bottom_p * (1 - top_p[..., 3:4])


def shape_mask(size, shape, ss=4):
    """Anti-aliased mask for a launcher shape filling a size x size square."""
    n = size * ss
    c = (np.arange(n) + 0.5) / n * 2 - 1
    X, Y = np.meshgrid(c, c)
    if shape == "circle":
        m = X ** 2 + Y ** 2 <= 1
    elif shape == "squircle":
        m = np.abs(X) ** 5 + np.abs(Y) ** 5 <= 1
    elif shape == "rounded":
        r = 0.36  # ~ 16% corner radius of the full side
        qx, qy = np.maximum(np.abs(X) - (1 - r), 0), np.maximum(np.abs(Y) - (1 - r), 0)
        m = qx ** 2 + qy ** 2 <= r ** 2
    elif shape == "teardrop":
        # circle with a square bottom-right corner
        m = (X ** 2 + Y ** 2 <= 1) | ((X >= 0) & (Y >= 0))
        r = 0.36
        qx, qy = np.maximum(X - (1 - r), 0), np.maximum(Y - (1 - r), 0)
        m &= ~((X > 1 - r) & (Y > 1 - r)) | (qx ** 2 + qy ** 2 <= r ** 2)
    else:
        raise ValueError(shape)
    m = m.astype(np.float64).reshape(size, ss, size, ss).mean((1, 3))
    return m


# --- Masks of the artwork -----------------------------------------------------
SVG_ZOOM = 2.5          # raster pixels per SVG unit (the SVG canvas is 512 units)
PLANET_SVG = (256.0, 194.0, 121.0)  # planet circle in SVG units (matches the clip in the SVG)


def render_layers(svg_path, hide):
    """Render the SVG with some top-level groups hidden; returns straight-alpha float RGBA."""
    css = "".join(f"#{g}{{display:none}}" for g in hide)
    png = resvg_py.svg_to_bytes(svg_path=svg_path, zoom=SVG_ZOOM, style_sheet=css or None)
    im = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
    return np.asarray(im, dtype=np.float64) / 255.0


class Art:
    """Layer masks of the hand-drawn icon SVG, in raster pixels.

    The SVG groups are ring-back, planet, ring-front, stars and keys; each mask is rendered
    from the SVG itself, so nothing is keyed or guessed from pixels.
    """

    def __init__(self, source):
        ALL = ["ring-back", "planet", "ring-front", "stars", "keys"]
        only = lambda *keep: render_layers(source, [g for g in ALL if g not in keep])  # noqa: E731
        self.rgba = rgba = render_layers(source, [])
        a = rgba[..., 3]
        H, W = a.shape
        keys_a = only("keys")[..., 3]
        stars_a = only("stars")[..., 3]
        planet_a = only("planet")[..., 3]
        front_a = only("ring-front")[..., 3]
        back_a = only("ring-back")[..., 3]
        self.keys = keys_a > 0.01
        self.stars = stars_a > 0.01
        self.planet_ring = (planet_a > 0.01) | (front_a > 0.01) | (back_a > 0.01)
        self.keys_bbox = _bbox(self.keys & (a > 0.01))
        cx, cy, rad = (v * SVG_ZOOM for v in PLANET_SVG)
        self.planet_circle = (cx, cy, rad)
        Y, X = np.mgrid[0:H, 0:W]
        self.disc = (X - cx) ** 2 + (Y - cy) ** 2 <= rad ** 2
        self.ring_front = front_a > 0.5
        self.ring_back = (back_a > 0.5) & ~self.ring_front & ~(planet_a > 0.5)
        self.ring = self.ring_front | self.ring_back

    def silhouette(self, keyboard=True, stars=True, gap=MONO_GAP, ring_grow=0):
        disc = self.disc
        front = ndi.binary_closing(self.ring_front, iterations=2)
        back_ring = self.ring_back
        if ring_grow:
            front = ndi.binary_dilation(front, iterations=ring_grow)
            back_ring = ndi.binary_dilation(back_ring, iterations=ring_grow)
        planet = disc & ~ndi.binary_dilation(front, iterations=gap)
        back = back_ring & ~front & ~ndi.binary_dilation(disc, iterations=gap)
        m = planet | front | back
        a = self.rgba[..., 3]
        if stars:
            m |= self.stars & (a > 0.5)
        if keyboard:
            m |= self.keys & (a > 0.5)
        return m


def _bbox(m):
    ys, xs = np.nonzero(m)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def _keep_large(m, min_area):
    lab, n = ndi.label(m)
    if n == 0:
        return m
    areas = ndi.sum(np.ones_like(lab), lab, index=np.arange(1, n + 1))
    return np.isin(lab, np.arange(1, n + 1)[areas >= min_area])


# --- Composition --------------------------------------------------------------
class Layout:
    """Maps source pixels into the 108dp adaptive canvas."""

    def __init__(self, art):
        a = art.rgba[..., 3] > 0.01
        kx0, ky0, kx1, ky1 = art.keys_bbox
        self.k_anchor = ((kx0 + kx1) / 2, ky0)
        self.k_scale = KEYBOARD_SCALE
        self.k_dst = (self.k_anchor[0], ky0 - KEYBOARD_RAISE)
        gy, gx = np.nonzero(a & ~art.keys)
        ky, kx = np.nonzero(a & art.keys)
        kx2, ky2 = self.kb_to_group(kx, ky)
        X = np.r_[gx, kx2]
        Y = np.r_[gy, ky2]
        self.cx = ART_CENTER_X
        self.cy = (Y.min() + Y.max() + 1) / 2
        R = np.sqrt((X - self.cx) ** 2 + (Y - self.cy) ** 2).max() + 1.0
        self.scale_dp = (SAFE_RADIUS_DP - SAFE_MARGIN_DP) / R  # dp per source px
        self.art_w_dp = (X.max() - X.min()) * self.scale_dp
        self.art_h_dp = (Y.max() - Y.min()) * self.scale_dp

    def kb_to_group(self, x, y):
        return ((x - self.k_anchor[0]) * self.k_scale + self.k_dst[0],
                (y - self.k_anchor[1]) * self.k_scale + self.k_dst[1])

    def render(self, art_arr, key_mask, px_per_dp, canvas_dp=108.0):
        """Warp a source array (premultiplied RGBA or mask) into the canvas."""
        size = int(round(canvas_dp * px_per_dp))
        s = self.scale_dp * px_per_dp
        ctr = (size / 2, size / 2)
        km = key_mask if art_arr.ndim == 2 else key_mask[..., None]
        group = warp(art_arr * (1 - km), s, (self.cx, self.cy), ctr, size)
        # the keyboard composes its own transform into group coordinates
        kdst = ((self.k_dst[0] - self.cx) * s + ctr[0], (self.k_dst[1] - self.cy) * s + ctr[1])
        kb = warp(art_arr * km, s * self.k_scale, self.k_anchor, kdst, size)
        return np.clip(group + kb, 0, 1)


# --- Vector tracing -----------------------------------------------------------
def trace_to_pathdata(mask, scale, offset=(0.0, 0.0)):
    """Trace a boolean mask with potrace; returns VectorDrawable pathData and flattened polygons."""
    # potracer fills pixels whose value is *below* blacklevel, so pass the inverse.
    bm = potrace.Bitmap(~mask.astype(bool))
    plist = bm.trace(turdsize=8, alphamax=1.0, opticurve=True, opttolerance=0.2)
    P = lambda p: np.array([p.x, p.y])  # noqa: E731
    f = lambda p: f"{p[0] * scale + offset[0]:.2f},{p[1] * scale + offset[1]:.2f}"  # noqa: E731
    parts = []
    polys = []
    for curve in plist:
        start = P(curve.start_point)
        parts.append("M" + f(start))
        poly = [start]
        prev = start
        for seg in curve.segments:
            end = P(seg.end_point)
            if seg.is_corner:
                c = P(seg.c)
                parts.append("L" + f(c) + "L" + f(end))
                poly += [c, end]
            else:
                c1, c2 = P(seg.c1), P(seg.c2)
                parts.append("C" + f(c1) + " " + f(c2) + " " + f(end))
                for t in np.linspace(0, 1, 12)[1:]:
                    poly.append((1 - t) ** 3 * prev + 3 * (1 - t) ** 2 * t * c1 + 3 * (1 - t) * t ** 2 * c2 + t ** 3 * end)
            prev = end
        parts.append("Z")
        polys.append([(p[0] * scale + offset[0], p[1] * scale + offset[1]) for p in poly])
    return "".join(parts), polys


def rasterize_polys(polys, size, scale, ss=4):
    """Even-odd rasterisation of traced polygons, for previewing the vector."""
    acc = np.zeros((size * ss, size * ss), bool)
    for poly in polys:
        im = Image.new("1", (size * ss, size * ss), 0)
        ImageDraw.Draw(im).polygon([(x * scale * ss, y * scale * ss) for x, y in poly], fill=1)
        acc ^= np.asarray(im)
    return acc.reshape(size, ss, size, ss).mean((1, 3))


def vector_xml(pathdata, w_dp, h_dp, vw, vh, comment, color="#FFFFFF"):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/branding/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w_dp:g}dp"
    android:height="{h_dp:g}dp"
    android:viewportWidth="{vw:g}"
    android:viewportHeight="{vh:g}">
    <path
        android:fillColor="{color}"
        android:fillType="evenOdd"
        android:pathData="{pathdata}"/>
</vector>
"""


# --- Main ---------------------------------------------------------------------
def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = "w" if isinstance(data, str) else "wb"
    with open(path, mode, newline="\n" if mode == "w" else None) as f:
        f.write(data)


def save_png(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, optimize=True)


def drop_shadow(alpha_img, offset, blur, opacity):
    sh = Image.new("L", alpha_img.size, 0)
    sh.paste(alpha_img, offset)
    sh = sh.filter(ImageFilter.GaussianBlur(blur))
    return sh.point(lambda v: int(v * opacity))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source", help="the icon SVG (not stored in the repo)")
    ap.add_argument("--previews", default=None)
    args = ap.parse_args()

    art = Art(args.source)
    lay = Layout(art)
    print(f"art {lay.art_w_dp:.1f}x{lay.art_h_dp:.1f}dp, scale {lay.scale_dp:.4f} dp/px, planet {art.planet_circle}")

    src_p = premul(art.rgba)
    keys_f = art.keys.astype(np.float64)
    M = MASTER_PX_PER_DP
    fg_master = lay.render(src_p, keys_f, M)  # premultiplied, 1728px
    bg_master = render_background(fg_master.shape[0])
    full_master = over(fg_master, bg_master)

    # 1. adaptive layers -------------------------------------------------------
    write(os.path.join(RES, "drawable", "ic_launcher_pluto_background.xml"), background_vector_xml())
    for dens, f in DENSITIES.items():
        n = int(round(108 * f))
        save_png(to_image(unpremul(resize_premul(fg_master, n))),
                 os.path.join(RES, f"drawable-{dens}", "ic_launcher_pluto_foreground.png"))

    sil = art.silhouette().astype(np.float64)
    mono_master = lay.render(sil, keys_f, M) > 0.5
    path, polys = trace_to_pathdata(mono_master, 1.0 / M)
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
          vector_xml(path, 108, 108, 108, 108, "Pluto Keyboard themed-icon (monochrome) layer."))

    # 2. small silhouette for notifications / IME subtype (planet + ring) -------
    sil_small = art.silhouette(keyboard=False, stars=False, gap=MONO_GAP + 8, ring_grow=6)
    x0, y0, x1, y1 = _bbox(sil_small)
    side = max(x1 - x0, y1 - y0)
    pad = side * (1.0 / 22.0)  # content 22dp inside 24dp
    box = side + 2 * pad
    ox, oy = (x0 + x1) / 2 - box / 2, (y0 + y1) / 2 - box / 2
    crop = np.zeros((int(math.ceil(box)) + 2,) * 2, bool)
    ys, xs = np.nonzero(sil_small)
    crop[(ys - oy).astype(int), (xs - ox).astype(int)] = True
    path_s, polys_s = trace_to_pathdata(crop, 24.0 / box)
    write(os.path.join(RES, "drawable", "pluto_logo_mono.xml"),
          vector_xml(path_s, 24, 24, 24, 24, "Pluto Keyboard planet mark, single colour."))

    # 3. colour in-app logo (planet + ring + stars) -----------------------------
    a = art.rgba[..., 3]
    x0, y0, x1, y1 = _bbox((art.planet_ring | art.stars) & (a > 0.01))
    p = 12
    logo = art.rgba[y0 - p:y1 + p, x0 - p:x1 + p].copy()
    logo[..., 3] *= ~art.keys[y0 - p:y1 + p, x0 - p:x1 + p]
    save_png(to_image(logo), os.path.join(RES, "drawable-nodpi", "pluto_logo.png"))

    # 4. legacy launcher icons ------------------------------------------------
    crop_px = 72 * M  # visible 72dp of the adaptive canvas
    o = 18 * M
    visible = full_master[o:o + crop_px, o:o + crop_px]
    for dens, f in DENSITIES.items():
        n = int(round(48 * f))
        inner = int(round(44 * f))
        art_img = resize_premul(visible, inner)
        for name, shape in (("ic_launcher", "rounded"), ("ic_launcher_round", "circle")):
            mask = shape_mask(inner, shape)
            tile = art_img * mask[..., None]
            canvas = np.zeros((n, n, 4))
            off = (n - inner) // 2
            canvas[off:off + inner, off:off + inner] = tile
            img = to_image(unpremul(canvas))
            shadow = drop_shadow(img.getchannel("A"), (0, max(1, int(round(f)))), 1.0 * f, 0.30)
            base = Image.new("RGBA", (n, n), (0, 0, 0, 0))
            base.putalpha(shadow)
            base.alpha_composite(img)
            save_png(base, os.path.join(RES, f"mipmap-{dens}", f"{name}.png"))

    save_png(to_image(unpremul(resize_premul(visible, 512))), os.path.join(REPO, "java", "ic_launcher-playstore.png"))

    # 5. docs icons use the original composition (art fills more of the tile) -------
    docs = os.path.join(REPO, "docs", "assets")
    hi = 1024
    doc_icon = render_doc_icon(art, lay, hi)
    for n in (512, 256):
        save_png(to_image(unpremul(resize_premul(doc_icon, n))), os.path.join(docs, f"pluto-icon-{n}.png"))
    banner = render_banner(doc_icon)
    save_png(banner, os.path.join(docs, "pluto-banner.png"))

    # 6. previews --------------------------------------------------------------
    if args.previews:
        render_previews(args.previews, fg_master, bg_master, polys, polys_s, M)


def render_doc_icon(art, lay, size):
    """Full icon in the source's own proportions (art ~78% of the tile width)."""
    canvas_dp = 72.0
    px_per_dp = size / canvas_dp
    # scale so that the art width matches the source proportion of the tile
    target_w_dp = canvas_dp * 0.78
    k = target_w_dp / lay.art_w_dp
    src_p = premul(art.rgba)
    s_save = lay.scale_dp
    lay.scale_dp = s_save * k
    fg = lay.render(src_p, art.keys.astype(np.float64), px_per_dp, canvas_dp=canvas_dp)
    lay.scale_dp = s_save
    bg = render_background(size, offset_dp=18.0)
    full = over(fg, bg)
    mask = shape_mask(size, "squircle")
    return full * mask[..., None]


def render_banner(doc_icon_p, W=1280, H=400):
    # background is the same navy gradient, stretched horizontally, with a glow behind the icon
    y = (np.arange(H) + 0.5) / H
    x = (np.arange(W) + 0.5) / W
    X, Y = np.meshgrid(x, y)
    lin = interp_stops(Y * 0.85 + X * 0.15, [(0.0, "#121A5A"), (0.55, "#0A0D38"), (1.0, "#07082A")])
    d = np.sqrt(((X - 0.16) * W / H) ** 2 + (Y - 0.45) ** 2) / 0.75
    glow = interp_stops(d, [(0.0, "#550A3A90"), (1.0, "#000A3A90")])
    a = glow[..., 3:4]
    rgb = lin[..., :3] * (1 - a) + glow[..., :3] * a
    base = to_image(np.dstack([rgb, np.ones((H, W))]))

    icon_size = 288
    icon = to_image(unpremul(resize_premul(doc_icon_p, icon_size)))
    ix, iy = 72, (H - icon_size) // 2
    sh = drop_shadow(icon.getchannel("A"), (0, 10), 18, 0.55)
    shadow_layer = Image.new("RGBA", (icon_size + 80, icon_size + 80), (2, 3, 16, 0))
    sh_big = Image.new("L", shadow_layer.size, 0)
    sh_big.paste(sh, (40, 40))
    sh_big = sh_big.filter(ImageFilter.GaussianBlur(4))
    shadow_layer.putalpha(sh_big)
    base.alpha_composite(shadow_layer, (ix - 40, iy - 40))
    # thin light rim so the navy tile separates from the navy banner
    rim = icon.getchannel("A").filter(ImageFilter.MaxFilter(5))
    rim_img = Image.new("RGBA", icon.size, (150, 160, 255, 0))
    rim_img.putalpha(rim.point(lambda v: int(v * 0.22)))
    base.alpha_composite(rim_img, (ix, iy))
    base.alpha_composite(icon, (ix, iy))

    fonts = r"C:\Windows\Fonts"
    title_font = ImageFont.truetype(os.path.join(fonts, "seguisb.ttf"), 104)
    tag_font = ImageFont.truetype(os.path.join(fonts, "segoeui.ttf"), 38)
    draw = ImageDraw.Draw(base)
    tx = ix + icon_size + 64
    title = "Pluto Keyboard"
    tag = "Private, offline typing and voice input"
    tb = draw.textbbox((0, 0), title, font=title_font)
    gb = draw.textbbox((0, 0), tag, font=tag_font)
    gap = 22
    total = (tb[3] - tb[1]) + gap + (gb[3] - gb[1])
    ty = (H - total) // 2 - tb[1]
    draw.text((tx, ty), title, font=title_font, fill=(246, 241, 255))
    draw.text((tx + 3, ty + tb[3] + gap - gb[1]), tag, font=tag_font, fill=(176, 182, 245))
    return base.convert("RGB")


def render_previews(out_dir, fg_master, bg_master, polys, polys_s, M):
    os.makedirs(out_dir, exist_ok=True)
    full = over(fg_master, bg_master)
    vis = full[18 * M:90 * M, 18 * M:90 * M]
    shapes = ["circle", "squircle", "rounded", "teardrop"]
    sizes = [48, 96, 192]
    pad = 16
    # colour icons
    W = len(shapes) * (sum(sizes) + pad * len(sizes)) + pad
    sheet = Image.new("RGBA", (W, 192 + 2 * pad), (232, 232, 236, 255))
    dark = Image.new("RGBA", (W, 192 + 2 * pad), (30, 30, 34, 255))
    x = pad
    for shp in shapes:
        for n in sizes:
            ic = resize_premul(vis, n) * shape_mask(n, shp)[..., None]
            im = to_image(unpremul(ic))
            sheet.alpha_composite(im, (x, pad + 192 - n))
            dark.alpha_composite(im, (x, pad + 192 - n))
            to_image(unpremul(resize_premul(vis, 432) * shape_mask(432, shp)[..., None])).save(
                os.path.join(out_dir, f"adaptive_{shp}_432.png"))
            x += n + pad
    sheet.save(os.path.join(out_dir, "adaptive_masks_light.png"))
    dark.save(os.path.join(out_dir, "adaptive_masks_dark.png"))

    # safe zone overlay on the full 108dp canvas
    big = to_image(unpremul(resize_premul(full, 540)))
    d = ImageDraw.Draw(big)
    c, r = 270, 33 * 5
    d.ellipse((c - r, c - r, c + r, c + r), outline=(255, 80, 80, 255), width=2)
    r2 = 36 * 5
    d.rectangle((c - r2, c - r2, c + r2, c + r2), outline=(80, 255, 80, 255), width=1)
    big.save(os.path.join(out_dir, "adaptive_safezone.png"))

    # monochrome (rasterised from the traced vector), themed-icon style
    mono = rasterize_polys(polys, 108 * 4, 4)  # 4 px/dp
    mono_vis = mono[72:360, 72:360]
    msheet = Image.new("RGBA", (2 * (sum(sizes) + pad * len(sizes)) + pad, 192 + 2 * pad), (232, 232, 236, 255))
    x = pad
    for theme_bg, theme_fg in (((211, 227, 253), (4, 30, 73)), ((0, 74, 119), (194, 231, 255))):
        for n in sizes:
            m = np.asarray(Image.fromarray((mono_vis * 255).astype(np.uint8)).resize((n, n), Image.LANCZOS)) / 255.0
            circ = shape_mask(n, "circle")
            rgb = np.array(theme_bg) / 255 * (1 - m[..., None]) + np.array(theme_fg) / 255 * m[..., None]
            msheet.alpha_composite(to_image(np.dstack([rgb, circ])), (x, pad + 192 - n))
            x += n + pad
    msheet.save(os.path.join(out_dir, "monochrome_themed.png"))
    Image.fromarray((mono * 255).astype(np.uint8)).save(os.path.join(out_dir, "monochrome_vector_raster.png"))

    # notification-size planet mark
    ms = rasterize_polys(polys_s, 96, 4)
    strip = Image.new("RGB", (24 + 48 + 96 + 4 * pad, 96 + 2 * pad), (40, 40, 44))
    x = pad
    for n in (24, 48, 96):
        mm = Image.fromarray((ms * 255).astype(np.uint8)).resize((n, n), Image.LANCZOS)
        strip.paste((235, 235, 240), (x, pad + 96 - n), mm)
        x += n + pad
    strip.save(os.path.join(out_dir, "pluto_logo_mono.png"))


