# --- Adaptive background definition (108dp canvas, visible area 18..90) --------
# Shared by the vector drawable and the Python renderer so they match.
BG_LINEAR = dict(y0=18.0, y1=90.0, stops=[(0.0, "#141B5E"), (0.45, "#0B0E3A"), (0.85, "#08092B"), (1.0, "#08092B")])
BG_RADIAL = dict(cx=66.0, cy=24.0, r=36.0, stops=[(0.0, "#660A3A90"), (1.0, "#000A3A90")])

# --- Composition of the foreground --------------------------------------------
SAFE_RADIUS_DP = 33.0      # adaptive icon safe zone (66dp circle)
SAFE_MARGIN_DP = 0.35      # keep anti-aliased edges clear of the zone boundary
KEYBOARD_SCALE = 0.90      # keyboard is drawn slightly narrower than in the source
KEYBOARD_RAISE = 0         # source px the keyboard moves up (the SVG spacing is already final)
ART_CENTER_X = 256.0 * 2.5  # planet / keyboard axis in the rendered SVG
MASTER_PX_PER_DP = 16      # master raster resolution (1728px for 108dp)
MONO_GAP = 13              # source px gap separating ring from planet in silhouettes


def hex_rgba(h):
    h = h.lstrip("#")
    if len(h) == 6:
        h = "FF" + h
    a, r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4, 6))
    return np.array([r, g, b, a])


def interp_stops(t, stops):
    t = np.clip(t, 0, 1)
    pos = np.array([s[0] for s in stops])
    cols = np.array([hex_rgba(s[1]) for s in stops])
    out = np.empty(t.shape + (4,))
    for c in range(4):
        out[..., c] = np.interp(t, pos, cols[:, c])
    return out


def render_background(size, canvas_dp=108.0, offset_dp=0.0):
    """Render the adaptive background. `offset_dp` crops into the canvas."""
    n = size
    span = canvas_dp - 2 * offset_dp
    coords = offset_dp + (np.arange(n) + 0.5) / n * span
    X, Y = np.meshgrid(coords, coords)
    lin = interp_stops((Y - BG_LINEAR["y0"]) / (BG_LINEAR["y1"] - BG_LINEAR["y0"]), BG_LINEAR["stops"])
    d = np.sqrt((X - BG_RADIAL["cx"]) ** 2 + (Y - BG_RADIAL["cy"]) ** 2) / BG_RADIAL["r"]
    rad = interp_stops(d, BG_RADIAL["stops"])
    a = rad[..., 3:4]
    rgb = lin[..., :3] * (1 - a) + rad[..., :3] * a
    return np.dstack([rgb, np.ones((n, n))])


